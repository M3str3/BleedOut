fn strip_art_line(s: &str) -> &str {
    s.trim_end_matches(|c: char| c.is_whitespace() || c == '\u{2800}')
}

fn term_width() -> usize {
    if let Some(w) = std::env::var("COLUMNS")
        .ok()
        .and_then(|v| v.parse::<usize>().ok())
        .filter(|w| *w > 0)
    {
        return w;
    }

    #[cfg(windows)]
    {
        if let Some(w) = windows_cols() {
            return w;
        }
    }

    80
}

#[cfg(windows)]
fn windows_cols() -> Option<usize> {
    use winapi::um::handleapi::INVALID_HANDLE_VALUE;
    use winapi::um::processenv::GetStdHandle;
    use winapi::um::winbase::STD_OUTPUT_HANDLE;
    use winapi::um::wincon::{GetConsoleScreenBufferInfo, CONSOLE_SCREEN_BUFFER_INFO};

    unsafe {
        let handle = GetStdHandle(STD_OUTPUT_HANDLE);
        if handle.is_null() || handle == INVALID_HANDLE_VALUE {
            return None;
        }
        let mut info: CONSOLE_SCREEN_BUFFER_INFO = std::mem::zeroed();
        if GetConsoleScreenBufferInfo(handle, &mut info) == 0 {
            return None;
        }
        let cols = info.srWindow.Right - info.srWindow.Left + 1;
        if cols > 0 {
            Some(cols as usize)
        } else {
            None
        }
    }
}

fn center_block(text: &str, width: usize) -> String {
    let lines: Vec<&str> = text.lines().map(strip_art_line).collect();
    let max = lines.iter().map(|l| l.chars().count()).max().unwrap_or(0);
    let pad = width.saturating_sub(max) / 2;
    let indent = " ".repeat(pad);
    lines
        .iter()
        .map(|line| format!("{indent}{line}"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Banner on top, ASCII art below, each block centered to the terminal width.
pub fn banner_text() -> String {
    let width = term_width();
    format!(
        "{}\n{}",
        center_block(BANNER, width),
        center_block(ASCII_ART, width)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn center_block_keeps_shape() {
        let block = center_block("ab\nabcd\na", 10);
        let lines: Vec<&str> = block.lines().collect();
        assert_eq!(lines[0], "   ab");
        assert_eq!(lines[1], "   abcd");
        assert_eq!(lines[2], "   a");
    }

    #[test]
    fn banner_then_ascii_centered() {
        let text = banner_text();
        let lines: Vec<&str> = text.lines().collect();
        assert!(text.contains('_'));
        let ascii_idx = lines.iter().position(|l| l.contains('_')).unwrap();
        let banner_idx = lines
            .iter()
            .position(|l| l.contains('⣿') || l.contains('⣤'))
            .unwrap();
        assert!(banner_idx < ascii_idx);
    }
}
